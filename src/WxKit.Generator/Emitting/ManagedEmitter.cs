using WxKit.Generator.Binding;

namespace WxKit.Generator.Emitting;

// Writes the managed API: a partial class for each bound class, the event types, the style enums,
// and the table that lets WxKit wrap native objects it did not create. Hand-written partials sit
// beside the generated ones and add what the generator cannot know.
internal static class ManagedEmitter {
	// Code marked as generated has nullable annotations off unless it turns them back on.
	public const string Banner = "// <auto-generated> Written by scripts/generate.ps1 from the wxWidgets interface headers. Do not edit. </auto-generated>\n#nullable enable";

	public static IEnumerable<(string FileName, string Text)> Files(BindingResult result) {
		foreach (BoundClass bound in result.Classes.Where(static bound => !bound.Tweak.IsHandwritten)) yield return ($"{bound.Name}.g.cs", Class(bound));
		yield return ("EventType.g.cs", EventTypes(result));
		yield return ("Styles.g.cs", Styles(result));
		yield return ("Enums.g.cs", Enums(result));
		yield return ("ObjectRegistry.g.cs", Factories(result));
	}

	private static CodeWriter Start() => new CodeWriter().Line(Banner).Line("using WxKit.Interop;").Line().Line("namespace WxKit;").Line();

	private static string Class(BoundClass bound) {
		CodeWriter writer = Start();
		Summary(writer, $"{Sentence(bound.Source.Brief)}Wraps {bound.CppName}.");
		string baseList = bound.Base is not null ? " : " + bound.Base.Name : bound.Handle.IsOwned ? " : NativeObject" : string.Empty;
		writer.Open($"public unsafe partial class {bound.Name}{baseList}");
		bool first = true;
		void Gap() {
			if (!first) writer.Line();
			first = false;
		}
		foreach (BoundFunction constructor in bound.Constructors) {
			Gap();
			Summary(writer, constructor.Source.Brief);
			string arguments = string.Join(", ", constructor.ManagedParameters.Select(static parameter => parameter.Name));
			writer.Open($"public {bound.Name}({ParameterList(constructor.ManagedParameters, withDefaults: true)}) : this(CreateNative({arguments}))").Close();
		}
		if (bound.Handle == HandleKind.Owned) {
			Gap();
			writer.Open($"internal {bound.Name}(WxkObject* native) : base(native)").Close();
		} else if (bound.Handle == HandleKind.Value) {
			Gap();
			writer.Open($"internal {bound.Name}(WxkObject* native) : base(native)").Close();
			writer.Line();
			writer.Line("// Takes ownership of a copy the shim hands out, which is null when the value was empty.");
			writer.Line($"internal static {(bound.Base is null ? string.Empty : "new ")}{bound.Name}? Take(WxkObject* native) => native is null ? null : new {bound.Name}(native);");
		} else if (bound.Base is not null) {
			Gap();
			// A base with another kind of handle, such as EvtHandler under Window, takes it as its own kind.
			string handle = bound.Base.Handle == bound.Handle ? "native" : $"({bound.Base.Handle.InteropType}*)native";
			writer.Open($"internal {bound.Name}({bound.Handle.InteropType}* native) : base({handle})").Close();
		}
		foreach (BoundProperty property in bound.Properties.OrderBy(static property => property.Name, StringComparer.Ordinal)) {
			Gap();
			WriteProperty(writer, bound, property);
		}
		foreach (BoundEvent boundEvent in bound.Events.OrderBy(static boundEvent => boundEvent.Name, StringComparer.Ordinal)) {
			Gap();
			Summary(writer, boundEvent.Description);
			string type = $"EventType.{boundEvent.Type.Name}";
			writer.Open($"public event EventHandler<{boundEvent.Type.EventClass.Name}>? {boundEvent.Name}");
			writer.Line($"add => AddHandler({type}, StandardId.Any, StandardId.Any, value, this);");
			writer.Line($"remove => RemoveHandler({type}, StandardId.Any, StandardId.Any, value);");
			writer.Close();
		}
		foreach (BoundMethod method in bound.Methods.OrderBy(static method => method.Name, StringComparer.Ordinal)) {
			Gap();
			WriteMethod(writer, bound, method);
		}
		foreach (BoundFunction constructor in bound.Constructors) {
			Gap();
			writer.Open($"private static {bound.Handle.InteropType}* CreateNative({ParameterList(constructor.ManagedParameters, withDefaults: false)})");
			// The thread is checked before anything is created, so a call on the wrong thread leaves nothing behind.
			writer.Line("Application.VerifyAccess();");
			WriteCall(writer, constructor, self: null, result => $"return {result};");
			writer.Close();
		}
		writer.Close();
		return writer.ToString();
	}

	private static void WriteProperty(CodeWriter writer, BoundClass bound, BoundProperty property) {
		Summary(writer, property.Getter.Source.Brief);
		string type = property.Getter.Returns.ManagedReturnType(nullable: property.Getter.Returns is ObjectConversion or AnyObjectConversion);
		if (property.Setter is null && IsSimple(property.Getter)) {
			writer.Line($"public {type} {property.Name} => {Call(bound, property.Getter, property.Getter.Returns.ManagedReturn)};");
			return;
		}
		writer.Open($"public {type} {property.Name}");
		if (IsSimple(property.Getter)) {
			writer.Line($"get => {Call(bound, property.Getter, property.Getter.Returns.ManagedReturn)};");
		} else {
			writer.Open("get");
			WriteCall(writer, property.Getter, bound.Handle.Accessor, result => $"return {property.Getter.Returns.ManagedReturn(result)};");
			writer.Close();
		}
		if (property.Setter is BoundFunction setter) {
			// A value object set to null is set to its empty one, which for a window's font or cursor restores the default.
			BoundParameter value = setter.Parameters[0] with { Name = "value", Nullable = setter.Parameters[0].Nullable || setter.Parameters[0].Conversion is ValueConversion };
			BoundFunction renamed = new(setter.Owner, setter.Source, setter.Returns, [value], isConstructor: false) { ExportName = setter.ExportName };
			if (IsSimple(renamed)) {
				writer.Line($"set => {Call(bound, renamed, static result => result)};");
			} else {
				writer.Open("set");
				WriteCall(writer, renamed, bound.Handle.Accessor, static result => $"{result};");
				writer.Close();
			}
		}
		writer.Close();
	}

	private static void WriteMethod(CodeWriter writer, BoundClass bound, BoundMethod method) {
		BoundFunction function = method.Function;
		Summary(writer, function.Source.Brief);
		string returns = function.Returns.ManagedReturnType(nullable: function.Returns is ObjectConversion or AnyObjectConversion);
		string signature = $"public {returns} {method.Name}({ParameterList(function.ManagedParameters, withDefaults: true)})";
		bool isVoid = function.Returns is VoidConversion;
		if (IsSimple(function)) {
			writer.Line($"{signature} => {Call(bound, function, function.Returns.ManagedReturn)};");
			return;
		}
		writer.Open(signature);
		WriteCall(writer, function, bound.Handle.Accessor, result => isVoid ? $"{result};" : $"return {function.Returns.ManagedReturn(result)};");
		writer.Close();
	}

	// A call needs a block when a parameter has to be checked for null or pinned first.
	private static bool IsSimple(BoundFunction function) => function.Parameters.All(static parameter => parameter.Conversion.Check(parameter.Name, parameter.Nullable) is null && parameter.Conversion.Fixed(parameter.Name) is null && parameter.Conversion.Prepare(parameter.Name) is null);

	private static string Call(BoundClass bound, BoundFunction function, Func<string, string> finish) => finish(InteropCall(function, bound.Handle.Accessor));

	private static string InteropCall(BoundFunction function, string? self) {
		List<string> arguments = self is null ? [] : [self];
		arguments.AddRange(function.Parameters.SelectMany(static parameter => parameter.Conversion.InteropArguments(parameter.Name, parameter.Nullable)));
		return $"WxKitNative.{function.InteropName}({string.Join(", ", arguments)})";
	}

	private static void WriteCall(CodeWriter writer, BoundFunction function, string? self, Func<string, string> statement) {
		foreach (BoundParameter parameter in function.ManagedParameters) {
			if (parameter.Conversion.Check(parameter.Name, parameter.Nullable) is string check) writer.Line(check);
		}
		foreach (BoundParameter parameter in function.Parameters) {
			if (parameter.Conversion.Prepare(parameter.Name) is string prepare) writer.Line(prepare);
		}
		List<string> pins = [.. function.Parameters.Select(static parameter => parameter.Conversion.Fixed(parameter.Name)).OfType<string>()];
		string call = statement(InteropCall(function, self));
		if (pins.Count == 0) {
			writer.Line(call);
			return;
		}
		foreach (string pin in pins.SkipLast(1)) writer.Line(pin);
		writer.Open(pins[^1]);
		writer.Line(call);
		writer.Close();
	}

	private static string ParameterList(IEnumerable<BoundParameter> parameters, bool withDefaults) => string.Join(", ", parameters.Select(parameter => {
		string declaration = $"{parameter.Conversion.ManagedType(parameter.Nullable)} {parameter.Name}";
		return withDefaults && parameter.Default is string value ? $"{declaration} = {value}" : declaration;
	}));

	private static string EventTypes(BindingResult result) {
		CodeWriter writer = Start();
		writer.Open("public static unsafe partial class EventType");
		bool first = true;
		foreach (BoundEventType type in result.EventTypes) {
			if (!first) writer.Line();
			first = false;
			Summary(writer, $"Wraps {type.Constant}.");
			writer.Line($"public static EventType<{type.EventClass.Name}> {type.Name} {{ get; }} = new(WxKitNative.EventType{type.Name}, static native => new {type.EventClass.Name}((WxkEvent*)native));");
		}
		writer.Close();
		return writer.ToString();
	}

	private static string Styles(BindingResult result) {
		CodeWriter writer = new CodeWriter().Line(Banner).Line().Line("namespace WxKit;");
		foreach (BoundClass bound in result.Classes) {
			if (bound.Styles is not BoundStyles styles) continue;
			writer.Line();
			Summary(writer, $"Styles for <see cref=\"{bound.Name}\"/>.", escape: false);
			writer.Line("[Flags]");
			writer.Open($"public enum {styles.Name} : long");
			foreach (BoundStyle style in styles.Members) {
				Summary(writer, style.Description.Length > 0 ? $"{Sentence(style.Description)}Wraps {style.Constant}." : $"Wraps {style.Constant}.");
				writer.Line($"{style.Name} = 0x{style.Value:X},");
			}
			writer.Close();
		}
		return writer.ToString();
	}

	private static string Enums(BindingResult result) {
		CodeWriter writer = new CodeWriter().Line(Banner).Line().Line("namespace WxKit;");
		foreach (BoundEnum bound in result.Enums) {
			writer.Line();
			Summary(writer, $"Wraps {bound.CppName}.");
			writer.Open($"public enum {bound.Name}");
			foreach (BoundStyle member in bound.Members) {
				Summary(writer, member.Description.Length > 0 ? $"{Sentence(member.Description)}Wraps {member.Constant}." : $"Wraps {member.Constant}.");
				writer.Line($"{member.Name} = {member.Value},");
			}
			writer.Close();
		}
		return writer.ToString();
	}

	private static string Factories(BindingResult result) {
		CodeWriter writer = Start();
		writer.Open("internal static unsafe partial class ObjectRegistry");
		writer.Line("// The managed class to wrap each wxWidgets class in, for objects WxKit did not create.");
		writer.Line("private static readonly Dictionary<string, Func<nint, EvtHandler>> Factories = new(StringComparer.Ordinal) {");
		foreach (BoundClass bound in result.Classes.Where(static bound => bound.Handle.IsEvtHandler && (bound.Tweak.IsHandwritten ? bound.Tweak.IsWrappable : true))) {
			writer.Line($"\t[\"{bound.CppName}\"] = static native => new {bound.Name}(({bound.Handle.InteropType}*)native),");
		}
		writer.Line("};");
		writer.Close();
		return writer.ToString();
	}

	private static void Summary(CodeWriter writer, string text, bool escape = true) {
		if (text.Length == 0) return;
		writer.Line($"/// <summary>{(escape ? CodeWriter.Escape(text) : text)}</summary>");
	}

	// Ends a description with a full stop and a space, so a sentence can follow it.
	private static string Sentence(string text) {
		string trimmed = text.Trim();
		if (trimmed.Length == 0) return string.Empty;
		return trimmed.EndsWith('.') ? trimmed + " " : trimmed + ". ";
	}
}
